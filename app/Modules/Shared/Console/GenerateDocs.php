<?php

namespace App\Modules\Shared\Console;

use App\Modules\Shared\Enums\PermissionAction;
use App\Modules\Shared\Services\PermissionRegistry;
use Illuminate\Console\Command;
use Illuminate\Routing\Route as LaravelRoute;
use Illuminate\Support\Facades\File;
use Illuminate\Support\Facades\Route;

/**
 * Writes the documentation that must always match the code: the permission matrix and the route inventory.
 * Run it after adding a form, a permission or a route (`php artisan formezy:docs`).
 */
class GenerateDocs extends Command
{
    protected $signature = 'formezy:docs {--path= : Directory to write into (default: docs/)}';

    protected $description = 'Generate docs/permission-matrix.md and docs/route-inventory.md from the code';

    public function handle(): int
    {
        $directory = $this->option('path') ?: base_path('docs');
        File::ensureDirectoryExists($directory);

        File::put($directory.DIRECTORY_SEPARATOR.'permission-matrix.md', $this->permissionMatrix());
        File::put($directory.DIRECTORY_SEPARATOR.'route-inventory.md', $this->routeInventory());

        $this->components->info("Documentation written to {$directory}");

        return self::SUCCESS;
    }

    private function permissionMatrix(): string
    {
        $actions = PermissionAction::cases();
        $forms = PermissionRegistry::forms();

        $md = "# Permission matrix\n\n";
        $md .= "_Generated by `php artisan formezy:docs` from `PermissionRegistry` — do not edit by hand._\n\n";
        $md .= 'Permissions are named `{form}.{action}`. A tick means the action exists for that form; whether a role holds it is ';
        $md .= 'set in *Administration → Roles & permissions* (defaults below). There is no implicit bypass: ';
        $md .= "**Super Admin** is an ordinary role that the seeder keeps granted with every permission.\n\n";

        $md .= '| Form | Group | '.implode(' | ', array_map(fn (PermissionAction $a) => $a->label(), $actions))." |\n";
        $md .= '|---|---|'.str_repeat(':-:|', count($actions))."\n";

        foreach ($forms as $key => $form) {
            $applicable = array_map(fn (PermissionAction $a) => $a->value, $form['actions']);
            $cells = array_map(fn (PermissionAction $a) => in_array($a->value, $applicable, true) ? '✓' : '', $actions);
            $md .= "| {$form['label']} (`{$key}`) | {$form['group']} | ".implode(' | ', $cells)." |\n";
        }

        $md .= "\n## Special permissions\n\n| Permission | Meaning |\n|---|---|\n";
        foreach (PermissionRegistry::special() as $name => $description) {
            $md .= "| `{$name}` | {$description} |\n";
        }

        $md .= "\n## Default role grants\n\n";
        $md .= "Applied only when a role is first created; later edits in the UI are never overwritten by re-seeding.\n\n";
        $md .= "### Super Admin\n\nEvery permission above, re-synced on each seeder run.\n\n";

        foreach (PermissionRegistry::defaultRoles() as $role => $permissions) {
            $byForm = [];
            foreach ($permissions as $permission) {
                [$form, $action] = explode('.', $permission, 2);
                $byForm[$form][] = $action;
            }
            ksort($byForm);

            $md .= "### {$role}\n\n";
            foreach ($byForm as $form => $formActions) {
                $md .= "- `{$form}`: ".implode(', ', $formActions)."\n";
            }
            $md .= "\n";
        }

        return $md;
    }

    private function routeInventory(): string
    {
        $md = "# Route inventory\n\n";
        $md .= "_Generated by `php artisan formezy:docs` — do not edit by hand._\n\n";
        $md .= "| Method | URI | Name | Handler | Middleware |\n|---|---|---|---|---|\n";

        $routes = collect(Route::getRoutes()->getRoutes())
            ->reject(fn (LaravelRoute $route) => str_starts_with($route->uri(), 'livewire') || in_array($route->uri(), ['up', 'storage/{path}'], true))
            ->sortBy(fn (LaravelRoute $route) => $route->uri());

        foreach ($routes as $route) {
            $methods = array_values(array_diff($route->methods(), ['HEAD']));
            $method = count($methods) > 3 ? 'ANY' : implode('/', $methods);   // Route::redirect() answers every verb
            $handler = $route->action['livewire_component'] ?? ($route->getActionName() === 'Closure' ? 'Closure' : $route->getActionName());
            $handler = is_string($handler) ? class_basename($handler) : 'Livewire component';
            $middleware = collect($route->gatherMiddleware())->filter(fn ($m) => is_string($m))->map(fn ($m) => class_basename($m))->implode(', ');

            $uri = '/'.ltrim($route->uri(), '/');
            $md .= "| {$method} | `{$uri}` | ".($route->getName() ? "`{$route->getName()}`" : '')." | {$handler} | {$middleware} |\n";
        }

        return $md;
    }
}
